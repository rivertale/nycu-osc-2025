// for pin XY (in decimal), it's fsel mask is GPIO_FSEL_MASK(Y) at GPIO_FSEL_REG(X)
#define GPIO_FSEL_MASK(pin_low_digit) (7 << (pin_low_digit * 3))
#define GPIO_FSEL_INPUT(pin_low_digit) (0 << (pin_low_digit * 3))
#define GPIO_FSEL_OUTPUT(pin_low_digit) (1 << (pin_low_digit * 3))
#define GPIO_FSEL_ALT0(pin_low_digit) (4 << (pin_low_digit * 3))
#define GPIO_FSEL_ALT1(pin_low_digit) (5 << (pin_low_digit * 3))
#define GPIO_FSEL_ALT2(pin_low_digit) (6 << (pin_low_digit * 3))
#define GPIO_FSEL_ALT3(pin_low_digit) (7 << (pin_low_digit * 3))
#define GPIO_FSEL_ALT4(pin_low_digit) (3 << (pin_low_digit * 3))
#define GPIO_FSEL_ALT5(pin_low_digit) (2 << (pin_low_digit * 3))

